--   activity_blocks: 유저당 ACTIVE row는 최대 1개 (재차단 시 기존 row의 expires_at을 연장)
--   block_appeals: 차단된 유저가 관리자에게 보내는 이의제기 메시지
-- ============================================================

CREATE TABLE activity_blocks
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       TIMESTAMP(6) NOT NULL,
    updated_at       TIMESTAMP(6) NOT NULL,
    target_user_id   BIGINT       NOT NULL,
    blocker_user_id  BIGINT       NOT NULL,
    item_id          BIGINT       NOT NULL,
    price            BIGINT       NOT NULL,
    expires_at       TIMESTAMP(6) NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    CONSTRAINT fk_activity_blocks_target FOREIGN KEY (target_user_id) REFERENCES users (id),
    CONSTRAINT fk_activity_blocks_blocker FOREIGN KEY (blocker_user_id) REFERENCES users (id),
    CONSTRAINT fk_activity_blocks_item FOREIGN KEY (item_id) REFERENCES shop_items (id),
    CONSTRAINT ck_activity_blocks_status CHECK (status IN ('ACTIVE', 'EXPIRED', 'LIFTED'))
);

-- 유저당 ACTIVE 상태 차단은 하나만 존재 (재차단은 새 row가 아니라 기존 row의 expires_at 연장)
CREATE UNIQUE INDEX uk_activity_blocks_active_target ON activity_blocks (target_user_id) WHERE status = 'ACTIVE';
CREATE INDEX idx_activity_blocks_status_expires ON activity_blocks (status, expires_at);

CREATE TABLE block_appeals
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at         TIMESTAMP(6) NOT NULL,
    activity_block_id  BIGINT       NOT NULL,
    sender_user_id     BIGINT       NOT NULL,
    message            TEXT         NOT NULL,
    handled            BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_block_appeals_block FOREIGN KEY (activity_block_id) REFERENCES activity_blocks (id),
    CONSTRAINT fk_block_appeals_sender FOREIGN KEY (sender_user_id) REFERENCES users (id)
);

CREATE INDEX idx_block_appeals_handled ON block_appeals (handled);
