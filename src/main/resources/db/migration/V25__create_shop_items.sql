-- ============================================================
-- V25: 상점(shop) 상품 카탈로그
--   BLOCK: 정가로 판매되는 임시 활동 차단권 (price/duration_minutes 사용)
--   ROLE_AUCTION: 주기적으로 경매가 열리는 UserRole 판매 설정 (target_role~cadence_days 사용)
--   가격/수량 등은 ROOT만 조정 가능 (상점이 자기강화 루프를 만들지 않도록)
-- ============================================================

CREATE TABLE shop_items
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at        TIMESTAMP(6) NOT NULL,
    updated_at        TIMESTAMP(6) NOT NULL,
    type              VARCHAR(20)  NOT NULL,
    name              VARCHAR(100) NOT NULL,
    -- BLOCK 전용
    price             BIGINT,
    duration_minutes  BIGINT,
    -- ROLE_AUCTION 전용
    target_role       VARCHAR(20),
    quantity          INT,
    min_price         BIGINT,
    duration_days     INT,
    cadence_days      INT,
    active            BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_shop_items_type CHECK (type IN ('BLOCK', 'ROLE_AUCTION')),
    CONSTRAINT ck_shop_items_fields_by_type CHECK (
        (type = 'BLOCK' AND price IS NOT NULL AND duration_minutes IS NOT NULL
            AND target_role IS NULL AND quantity IS NULL AND min_price IS NULL
            AND duration_days IS NULL AND cadence_days IS NULL)
        OR
        (type = 'ROLE_AUCTION' AND price IS NULL AND duration_minutes IS NULL
            AND target_role IS NOT NULL AND quantity IS NOT NULL AND min_price IS NOT NULL
            AND duration_days IS NOT NULL AND cadence_days IS NOT NULL)
        ),
    -- ROOT 권한은 경매/판매 대상으로 등록할 수 없다 (자기강화 루프 방지)
    CONSTRAINT ck_shop_items_target_role_not_root CHECK (target_role IS NULL OR target_role <> 'ROOT')
);

CREATE INDEX idx_shop_items_type_active ON shop_items (type, active);

