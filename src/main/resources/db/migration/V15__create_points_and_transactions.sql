-- ============================================================
-- V15: 포인트 원장(points) / 거래 기록(transactions) 테이블 생성
--   points: 유저별 잔고. user_id가 NULL인 단일 행은 시스템(중앙) 계정 —
--           포인트 발행의 원천이며, 매점처럼 잔액이 음수가 될 수 있다.
--   transactions: 모든 포인트 증감 이력. append-only, 수정 없음.
-- ============================================================

CREATE TABLE points
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    user_id    BIGINT,
    balance    BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT fk_points_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_points_user_id UNIQUE (user_id),
    -- 시스템 계정(user_id IS NULL)만 잔액이 음수가 될 수 있다
    CONSTRAINT ck_points_balance_non_negative CHECK (user_id IS NULL OR balance >= 0)
);

-- user_id가 NULL인 행(시스템 계정)은 단 하나만 존재할 수 있다
CREATE UNIQUE INDEX uk_points_system_account ON points ((1)) WHERE user_id IS NULL;

-- 시스템(중앙) 계정 시드 — 잔고 0에서 시작해 지급 시마다 음수 방향으로 발행량이 누적됨
INSERT INTO points (created_at, updated_at, user_id, balance)
VALUES (now(), now(), NULL, 0);

CREATE TABLE transactions
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id              BIGINT,
    recipient_id           BIGINT,
    amount                 BIGINT       NOT NULL CHECK (amount > 0),
    type                   VARCHAR(20)  NOT NULL,
    prev_sender_balance    BIGINT       NOT NULL,
    post_sender_balance    BIGINT       NOT NULL,
    prev_recipient_balance BIGINT       NOT NULL,
    post_recipient_balance BIGINT       NOT NULL,
    message                VARCHAR(255),
    created_at             TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_transactions_sender FOREIGN KEY (sender_id) REFERENCES users (id),
    CONSTRAINT fk_transactions_recipient FOREIGN KEY (recipient_id) REFERENCES users (id),
    CONSTRAINT ck_transactions_type CHECK (type IN ('GRANT', 'COLLECT')),
    -- 송금인/수취인이 동시에 시스템 계정(NULL)이거나 동일 계정일 수 없다
    CONSTRAINT ck_transactions_sender_recipient_distinct CHECK (sender_id IS DISTINCT FROM recipient_id)
    );

CREATE INDEX idx_transactions_sender ON transactions (sender_id);
CREATE INDEX idx_transactions_recipient ON transactions (recipient_id);