CREATE TABLE check_in_logs
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT    NOT NULL REFERENCES users (id),
    -- 출석으로 인정되는 KST 날짜. created_at(행이 쓰인 시각)과 구분한다 — 백필이나 보정 시 갈라진다.
    check_in_date DATE      NOT NULL,
    created_at    TIMESTAMP NOT NULL DEFAULT now(),
    -- 하루 1회 보장을 DB 레벨로 끌어올린다. 앱에서는 시스템 계정 락 + 이중 체크로 이미
    -- 막고 있어서 실제로 걸릴 일은 없고, 여기서는 백스톱 역할이다.
    CONSTRAINT uk_check_in_logs_user_date UNIQUE (user_id, check_in_date)
);

-- ------------------------------------------------------------
-- 기존 CHECKIN 원장을 옮겨온다.
--   - user_id: 지급(system->user)이면 recipient_id, 차감(user->system)이면 sender_id
--   - check_in_date: created_at은 V5 이후 KST 벽시계라 ::date 캐스팅이 그대로 KST 날짜다
-- 하루 2건이 존재할 가능성에 대비해 DISTINCT ON으로 하루 1건만 남긴다.
-- ------------------------------------------------------------
INSERT INTO check_in_logs (user_id, check_in_date, created_at)
SELECT DISTINCT ON (COALESCE(t.recipient_id, t.sender_id), t.created_at::date)
    COALESCE(t.recipient_id, t.sender_id),
    t.created_at::date,
    t.created_at
FROM transactions t
WHERE t.type = 'CHECKIN'
  AND COALESCE(t.recipient_id, t.sender_id) IS NOT NULL
ORDER BY COALESCE(t.recipient_id, t.sender_id), t.created_at::date, t.created_at;
