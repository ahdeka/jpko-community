-- ============================================================
-- V39: 룰렛 방어권(SHIELD)
--   shop_items에 SHIELD 타입 추가 — BLOCK과 동일하게 price/duration_minutes를 쓴다.
--   roulette_shields: 구매한 방어권 보유 현황. 유저당 ACTIVE row는 최대 1개(재구매는 연장).
--   만료되면 구매 시점에 스냅샷해둔 previous_roulette_status로 원복한다(role_purchases와 동일한 패턴).
-- ============================================================

ALTER TABLE shop_items DROP CONSTRAINT ck_shop_items_type;
ALTER TABLE shop_items
    ADD CONSTRAINT ck_shop_items_type CHECK (type IN ('BLOCK', 'ROLE_AUCTION', 'SHIELD'));

ALTER TABLE shop_items DROP CONSTRAINT ck_shop_items_fields_by_type;
ALTER TABLE shop_items
    ADD CONSTRAINT ck_shop_items_fields_by_type CHECK (
        (type IN ('BLOCK', 'SHIELD') AND price IS NOT NULL AND duration_minutes IS NOT NULL
            AND target_role IS NULL AND quantity IS NULL AND min_price IS NULL
            AND duration_days IS NULL AND cadence_days IS NULL)
        OR
        (type = 'ROLE_AUCTION' AND price IS NULL AND duration_minutes IS NULL
            AND target_role IS NOT NULL AND quantity IS NOT NULL AND min_price IS NOT NULL
            AND duration_days IS NOT NULL AND cadence_days IS NOT NULL)
        );

ALTER TABLE transactions DROP CONSTRAINT ck_transactions_type;
ALTER TABLE transactions
    ADD CONSTRAINT ck_transactions_type
        CHECK (type IN ('GRANT', 'COLLECT', 'ACCOUNT_OPENED', 'CHECKIN',
                        'ROULETTE', 'ROULETTE_FEE', 'TRANSFER', 'TRANSFER_FEE',
                        'BLOCK_PURCHASE', 'BLOCK_UNBLOCK', 'BID_HOLD', 'BID_REFUND',
                        'SUSPEND_UNLOCK', 'JMT', 'SHIELD_PURCHASE'));

CREATE TABLE roulette_shields
(
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at                TIMESTAMP(6) NOT NULL,
    updated_at                TIMESTAMP(6) NOT NULL,
    user_id                   BIGINT       NOT NULL,
    item_id                   BIGINT       NOT NULL,
    price                     BIGINT       NOT NULL,
    previous_roulette_status  BOOLEAN      NOT NULL,
    expires_at                TIMESTAMP(6) NOT NULL,
    status                    VARCHAR(20)  NOT NULL,
    CONSTRAINT fk_roulette_shields_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_roulette_shields_item FOREIGN KEY (item_id) REFERENCES shop_items (id),
    CONSTRAINT ck_roulette_shields_status CHECK (status IN ('ACTIVE', 'EXPIRED'))
);

-- 유저당 ACTIVE 방어권은 하나만 (재구매는 새 row가 아니라 기존 row의 expires_at 연장)
CREATE UNIQUE INDEX uk_roulette_shields_active_user ON roulette_shields (user_id) WHERE status = 'ACTIVE';
CREATE INDEX idx_roulette_shields_status_expires ON roulette_shields (status, expires_at);
