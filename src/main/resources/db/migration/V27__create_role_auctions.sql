-- ============================================================
-- V27: 포인트 기반 ADMIN 권한 경매(#7)
--   role_auction_rounds: shop_items(type=ROLE_AUCTION)에서 주기적으로 열리는 경매 회차
--   role_bids: 회차별 입찰. 입찰 시점에 즉시 포인트 예탁(에스크로)
--   role_purchases: 낙찰로 보유 중인(또는 만료된) UserRole 현황. 만료 시 previous_role로 원복
-- ============================================================

CREATE TABLE role_auction_rounds
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    TIMESTAMP(6) NOT NULL,
    updated_at    TIMESTAMP(6) NOT NULL,
    shop_item_id  BIGINT       NOT NULL,
    target_role   VARCHAR(20)  NOT NULL,
    quantity      INT          NOT NULL,
    min_price     BIGINT       NOT NULL,
    start_at      TIMESTAMP(6) NOT NULL,
    end_at        TIMESTAMP(6) NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    CONSTRAINT fk_role_auction_rounds_item FOREIGN KEY (shop_item_id) REFERENCES shop_items (id),
    CONSTRAINT ck_role_auction_rounds_status CHECK (status IN ('OPEN', 'SETTLED'))
);

-- 상품(shop_item)당 OPEN 회차는 동시에 하나만 (중복 개설 방지)
CREATE UNIQUE INDEX uk_role_auction_rounds_open_item ON role_auction_rounds (shop_item_id) WHERE status = 'OPEN';
CREATE INDEX idx_role_auction_rounds_status_end ON role_auction_rounds (status, end_at);

CREATE TABLE role_bids
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6) NOT NULL,
    round_id        BIGINT       NOT NULL,
    bidder_user_id  BIGINT       NOT NULL,
    amount          BIGINT       NOT NULL CHECK (amount > 0),
    status          VARCHAR(20)  NOT NULL,
    CONSTRAINT fk_role_bids_round FOREIGN KEY (round_id) REFERENCES role_auction_rounds (id),
    CONSTRAINT fk_role_bids_bidder FOREIGN KEY (bidder_user_id) REFERENCES users (id),
    CONSTRAINT uk_role_bids_round_bidder UNIQUE (round_id, bidder_user_id),
    CONSTRAINT ck_role_bids_status CHECK (status IN ('ACTIVE', 'WON', 'LOST', 'CANCELLED'))
);

CREATE INDEX idx_role_bids_round_status_amount ON role_bids (round_id, status, amount DESC);

CREATE TABLE role_purchases
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     TIMESTAMP(6) NOT NULL,
    updated_at     TIMESTAMP(6) NOT NULL,
    user_id        BIGINT       NOT NULL,
    target_role    VARCHAR(20)  NOT NULL,
    previous_role  VARCHAR(20)  NOT NULL,
    expires_at     TIMESTAMP(6) NOT NULL,
    status         VARCHAR(20)  NOT NULL,
    CONSTRAINT fk_role_purchases_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_role_purchases_status CHECK (status IN ('ACTIVE', 'EXPIRED'))
);

-- 유저당 ACTIVE 낙찰 현황은 하나만 (재낙찰은 기존 row의 expires_at을 +7일 연장)
CREATE UNIQUE INDEX uk_role_purchases_active_user ON role_purchases (user_id) WHERE status = 'ACTIVE';
CREATE INDEX idx_role_purchases_status_expires ON role_purchases (status, expires_at);
